def checkNumber(skaitlis):
    if skaitlis > 0:
        print(f"Dotais skaitlis {skaitlis} ir pozitīvs")
    elif skaitlis < 0:
        print(f"Dotais skaitlis {skaitlis} ir negatīvs")
    else:
        print(f"Dotais skaitlis {skaitlis} ir nulle")


checkNumber(169)
checkNumber(-374)
checkNumber(0)
